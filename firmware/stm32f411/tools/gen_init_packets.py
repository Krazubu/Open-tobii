#!/usr/bin/env python3
"""Turn crates/tobii-usb/init_packets_ep.txt into a C array the firmware can
replay on bulk EP 0x05.

Each input line is `0x05<TAB><hex>`, where <hex> is one bulk OUT write:
`u32 LE channel` + `u32 LE length` + the TTP message. We keep the bytes as-is.

Usage:
    python3 tools/gen_init_packets.py \
        ../../crates/tobii-usb/init_packets_ep.txt > include/tobii_init.h
"""
import sys


def main() -> int:
    if len(sys.argv) != 2:
        sys.stderr.write(__doc__)
        return 2
    packets = []
    with open(sys.argv[1], "r", encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            ep, hexstr = line.split("\t", 1)
            if ep not in ("0x05", "5"):
                sys.stderr.write(f"skip non-0x05 line: {ep}\n")
                continue
            packets.append(bytes.fromhex(hexstr))

    out = sys.stdout
    out.write("/* Generated by tools/gen_init_packets.py — do not edit. */\n")
    out.write("#ifndef OPEN_TOBII_INIT_H\n#define OPEN_TOBII_INIT_H\n\n")
    out.write("#include <stddef.h>\n#include <stdint.h>\n\n")
    out.write("struct tobii_init_packet { const uint8_t *data; size_t len; };\n\n")
    for i, pkt in enumerate(packets):
        body = ", ".join(f"0x{b:02x}" for b in pkt)
        out.write(f"static const uint8_t tobii_init_{i}[] = {{ {body} }};\n")
    out.write("\nstatic const struct tobii_init_packet tobii_init_packets[] = {\n")
    for i, pkt in enumerate(packets):
        out.write(f"    {{ tobii_init_{i}, {len(pkt)} }},\n")
    out.write("};\n")
    out.write(f"\n#define TOBII_INIT_PACKET_COUNT {len(packets)}\n\n")
    out.write("#endif /* OPEN_TOBII_INIT_H */\n")
    sys.stderr.write(f"wrote {len(packets)} init packets\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
